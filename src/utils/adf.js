export const COUNTERPART_NOTICE_MARKER =
  'Jira Sync Connector notice: protected counterpart.';

export const RECONCILIATION_REVIEW_MARKER =
  'Jira Sync Connector recurring reconciliation review required.';

/**
 * Build a connector-owned review comment for a source issue that repeatedly
 * fails reconciliation. The marker is also used to keep this generated comment
 * out of every comment-copy path.
 */
export function buildReconciliationReviewCommentADF({
  localKey,
  reasonCode,
  attempts
} = {}) {
  const safeKey = typeof localKey === 'string' ? localKey : 'the source issue';
  const safeReason = typeof reasonCode === 'string' ? reasonCode : 'UNSPECIFIED';
  const safeAttempts = Number.isSafeInteger(attempts) && attempts > 0
    ? attempts
    : 1;
  return {
    type: 'doc',
    version: 1,
    content: [
      {
        type: 'paragraph',
        content: [
          {
            type: 'text',
            text: `${RECONCILIATION_REVIEW_MARKER} ${safeKey} could not be synchronized after ${safeAttempts} attempt(s). Reason code: ${safeReason}.`
          }
        ]
      },
      {
        type: 'paragraph',
        content: [
          {
            type: 'text',
            text: 'This comment is generated by the connector and is never synchronized. Review the attention record in Sync Connector > Sync Activity, then resolve it after a successful health check or acknowledge it to silence notifications.'
          }
        ]
      }
    ]
  };
}

/**
 * Detect connector-generated comments by their stable text markers. App-authored
 * comments are already skipped elsewhere; this marker check is a second,
 * content-based guard for generated review comments.
 */
export function isConnectorGeneratedComment(body) {
  if (!body) {
    return false;
  }
  const text = typeof body === 'object' ? extractTextFromADF(body) : String(body);
  const normalized = text.trimStart();
  if (normalized.startsWith(RECONCILIATION_REVIEW_MARKER)) {
    return true;
  }
  return /^\[Comment from [^\]]+ - User: [^\]]+\]:/.test(normalized);
}

export function extractTextFromADF(adf, skipCrossReference = true) {
  if (!adf || typeof adf !== 'object') return '';
  
  let text = '';
  
  function traverse(node, isFirstNode = false) {
    // Connector-owned notices must never be copied into a counterpart.
    if (isCounterpartNoticeNode(node)) {
      return;
    }
    // Skip cross-reference line if requested (old panel format or new minimal format)
    if (skipCrossReference) {
      // Old panel format
      if (node.type === 'panel' && 
          node.attrs?.panelType === 'info' &&
          node.content?.[0]?.content?.[0]?.text === '🔗 Synced Issue Reference') {
        return;
      }
      // New minimal format - paragraph starting with 🔗 and containing ↔
      if (node.type === 'paragraph' &&
          node.content?.[0]?.text?.startsWith('🔗 ') &&
          node.content?.[0]?.text?.includes(' ↔ ')) {
        return;
      }
      // Skip rule dividers that follow cross-reference
      if (node.type === 'rule') {
        return;
      }
    }
    
    if (node.type === 'text') {
      text += node.text;
    } else if (node.type === 'paragraph' && !isFirstNode && text.length > 0) {
      // Add line breaks between paragraphs
      text += '\n\n';
    } else if (node.type === 'hardBreak') {
      text += '\n';
    }
    
    if (node.content && Array.isArray(node.content)) {
      node.content.forEach((child, index) => traverse(child, index === 0 && isFirstNode));
    }
  }
  
  traverse(adf, true);
  return text.trim();
}

export async function replaceMediaIdsInADF(adf, attachmentMapping) {
  if (!adf || typeof adf !== 'object') return adf;
  
  // Deep clone to avoid mutating original
  const cloned = JSON.parse(JSON.stringify(adf));
  
  function traverse(node) {
    if (node.type === 'media' && node.attrs && node.attrs.id) {
      const localId = node.attrs.id;
      const remoteId = attachmentMapping[localId];
      if (remoteId) {
        console.log(`🖼️ Replacing media ID: ${localId} → ${remoteId}`);
        node.attrs.id = remoteId;
      } else {
        console.log(`⚠️ No mapping found for media ID: ${localId}`);
      }
    }
    
    if (node.content && Array.isArray(node.content)) {
      node.content.forEach(traverse);
    }
  }
  
  traverse(cloned);
  return cloned;
}

export function textToADFWithAuthor(text, orgName, userName) {
  const prefix = `[Comment from ${orgName} - User: ${userName}]:\n\n`;
  const fullText = prefix + (text || '');
  
  return {
    type: 'doc',
    version: 1,
    content: [
      buildParagraph(fullText)
    ]
  };
}

export function buildSyncedCommentADF({
  orgName,
  userName,
  parentAuthor,
  parentSnippet,
  responseText
}) {
  const header = `[Comment from ${orgName} - User: ${userName}]:`;
  const snippetText = parentSnippet ? `: "${parentSnippet}"` : '';
  const replyLine = parentAuthor
    ? `Replying to ${parentAuthor}${snippetText}`.trim()
    : parentSnippet
      ? `Replying to earlier comment${snippetText}`
      : '';

  const content = [buildParagraph(header)];

  if (replyLine) {
    content.push(buildParagraph(replyLine));
    content.push({ type: 'rule' });
  }

  content.push(buildParagraph(responseText || ''));

  return {
    type: 'doc',
    version: 1,
    content
  };
}

function buildParagraph(text) {
  if (!text) {
    return { type: 'paragraph', content: [] };
  }
  return {
    type: 'paragraph',
    content: [
      {
        type: 'text',
        text
      }
    ]
  };
}

export function textToADF(text) {
  if (!text || text.trim() === '') {
    return {
      type: 'doc',
      version: 1,
      content: []
    };
  }
  
  // Split by double line breaks for paragraphs
  const paragraphs = text.split(/\n\n+/).filter(p => p.trim());
  
  if (paragraphs.length === 0) {
    return {
      type: 'doc',
      version: 1,
      content: []
    };
  }
  
  const content = paragraphs.map(para => ({
    type: 'paragraph',
    content: [
      {
        type: 'text',
        text: para.trim()
      }
    ]
  }));
  
  return {
    type: 'doc',
    version: 1,
    content: content
  };
}

function isPlainObject(value) {
  return !!value && typeof value === 'object' && !Array.isArray(value);
}

function isValidAdfNode(node) {
  if (!isPlainObject(node) || typeof node.type !== 'string' || !node.type) {
    return false;
  }
  if (node.content !== undefined && !Array.isArray(node.content)) {
    return false;
  }
  if (Array.isArray(node.content) && !node.content.every(isValidAdfNode)) {
    return false;
  }
  if (node.marks !== undefined && !Array.isArray(node.marks)) {
    return false;
  }
  if (node.type === 'text' && typeof node.text !== 'string') {
    return false;
  }
  return true;
}

export function isValidADFDocument(adf) {
  return isPlainObject(adf)
    && adf.type === 'doc'
    && (adf.version === undefined || adf.version === 1)
    && Array.isArray(adf.content)
    && adf.content.every(isValidAdfNode);
}

function cloneAdf(value) {
  return JSON.parse(JSON.stringify(value));
}

function normalizeDescriptionToAdf(description) {
  if (description === null || description === undefined) {
    return { type: 'doc', version: 1, content: [] };
  }
  if (typeof description === 'string') {
    return textToADF(description);
  }
  if (!isValidADFDocument(description)) {
    return null;
  }
  return cloneAdf(description);
}

function isCrossReferenceParagraph(node) {
  return isPlainObject(node)
    && node.type === 'paragraph'
    && Array.isArray(node.content)
    && node.content.length === 1
    && node.content[0]?.type === 'text'
    && typeof node.content[0]?.text === 'string'
    && /^🔗 .+ ↔ .+$/.test(node.content[0].text);
}

function isLegacyCrossReferencePanel(node) {
  return isPlainObject(node)
    && node.type === 'panel'
    && node.attrs?.panelType === 'info'
    && node.content?.[0]?.content?.[0]?.text === '🔗 Synced Issue Reference';
}

/**
 * True for generated cross-reference boilerplate. Exported so hashing code can
 * ignore connector-owned description changes without logging description text.
 */
export function isCrossReferenceNode(node) {
  return isCrossReferenceParagraph(node) || isLegacyCrossReferencePanel(node);
}

/**
 * Remove connector-owned cross-reference paragraphs/panels from an ADF tree
 * without mutating the input. No other user content is removed.
 */
export function stripCrossReferenceFromADF(adf) {
  if (!isPlainObject(adf) || !Array.isArray(adf.content)) {
    return adf;
  }
  const cloned = cloneAdf(adf);
  cloned.content = cloned.content.filter(node => !isCrossReferenceNode(node));
  return cloned;
}

function contentWithoutCrossReference(adf) {
  return adf.content.filter(node => !isCrossReferenceNode(node));
}

function noticeParagraphText(node) {
  const first = node?.content?.[0];
  return first?.type === 'paragraph'
    ? first.content?.[0]?.text
    : node?.content?.[0]?.text;
}

function isCounterpartNoticeNode(node) {
  if (!isPlainObject(node) || node.type !== 'panel') {
    return false;
  }
  const text = noticeParagraphText(node);
  return typeof text === 'string' && text.startsWith(COUNTERPART_NOTICE_MARKER);
}

/**
 * True for the connector-owned survivor notice. Exported so hashing and
 * description-preservation checks can ignore only this generated boilerplate.
 */
export function isCounterpartNotice(node) {
  return isCounterpartNoticeNode(node);
}

/**
 * Remove connector-owned survivor notices without mutating the input. User
 * content and the existing cross-reference are preserved.
 */
export function stripCounterpartNoticeFromADF(adf) {
  if (!isPlainObject(adf) || !Array.isArray(adf.content)) {
    return adf;
  }
  const cloned = cloneAdf(adf);
  cloned.content = cloned.content.filter(node => !isCounterpartNoticeNode(node));
  return cloned;
}

/**
 * Return a new ADF document with exactly one marker-tagged survivor notice
 * followed by the original content. The input is never mutated. Returns null for
 * malformed descriptions so callers preserve the existing Jira description.
 */
export function prependCounterpartNoticeToADF(adf, { localKey, remoteKey, status } = {}) {
  const original = normalizeDescriptionToAdf(adf);
  if (!original) {
    return null;
  }

  const statusLabel = status === 'unavailable'
    ? 'is currently unavailable'
    : 'was deleted';
  const notice = {
    type: 'panel',
    attrs: { panelType: 'warning' },
    content: [
      {
        type: 'paragraph',
        content: [
          {
            type: 'text',
            text: `${COUNTERPART_NOTICE_MARKER} The counterpart issue for ${localKey || 'the local issue'} ↔ ${remoteKey || 'the remote issue'} ${statusLabel}. No Jira issue was deleted by this connector. An administrator can review this pair in Deleted Counterpart Recovery.`
          }
        ]
      }
    ]
  };

  return {
    ...original,
    content: [
      notice,
      ...original.content.filter(node => !isCounterpartNoticeNode(node))
    ]
  };
}

/**
 * Remove exactly one connector-owned notice and optionally prepend a fresh one.
 * Returns null when the description cannot be safely normalized.
 */
export function updateCounterpartNoticeInADF(adf, noticeInfo = null) {
  const original = normalizeDescriptionToAdf(adf);
  if (!original) {
    return null;
  }
  const withoutNotice = {
    ...original,
    content: original.content.filter(node => !isCounterpartNoticeNode(node))
  };
  return noticeInfo
    ? prependCounterpartNoticeToADF(withoutNotice, noticeInfo)
    : withoutNotice;
}

function contentWithoutConnectorBoilerplate(adf) {
  return adf.content.filter(node => !isCrossReferenceNode(node) && !isCounterpartNoticeNode(node));
}

/**
 * Return a new ADF document with exactly one cross-reference paragraph followed
 * by the original content. The input is never mutated.
 *
 * Returns null for malformed/unsupported descriptions so callers can preserve
 * the existing Jira description instead of writing an empty replacement.
 */
export function prependCrossReferenceToADF(adf, localKey, remoteKey) {
  const original = normalizeDescriptionToAdf(adf);
  if (!original) {
    return null;
  }

  const crossRefLine = {
    type: 'paragraph',
    content: [
      {
        type: 'text',
        text: `🔗 ${localKey} ↔ ${remoteKey}`,
        marks: [{ type: 'em' }]
      }
    ]
  };

  return {
    ...original,
    content: [crossRefLine, ...contentWithoutCrossReference(original)]
  };
}

export function adfPreservesOriginalContent(originalDescription, resultAdf) {
  if (!isValidADFDocument(resultAdf)) {
    return false;
  }
  const original = normalizeDescriptionToAdf(originalDescription);
  if (!original) {
    return false;
  }
  const expectedContent = contentWithoutConnectorBoilerplate(original);
  const resultContent = contentWithoutConnectorBoilerplate(resultAdf);
  return JSON.stringify(expectedContent) === JSON.stringify(resultContent);
}


const SYNC_PREFIX_REGEX = /^\[Comment from [^\]]+\]:\s*/i;
const ACCOUNT_MENTION_REGEX = /\[~accountid:[^\]]+\]/gi;

export function stripSyncPrefix(text) {
  if (!text) {
    return '';
  }
  return text.replace(SYNC_PREFIX_REGEX, '').trimStart();
}

export function sanitizeCommentText(text) {
  if (!text) {
    return '';
  }

  let result = text.replace(ACCOUNT_MENTION_REGEX, '');
  result = result.replace(/[ \t]+\n/g, '\n');
  result = result.replace(/\n{3,}/g, '\n\n');
  result = result.replace(/[ \t]{2,}/g, ' ');
  result = result.replace(/\n +/g, '\n');
  return result.trim();
}


